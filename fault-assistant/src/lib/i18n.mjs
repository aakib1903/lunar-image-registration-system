/** Looks up a string, falling back to English, then to the key. */
export function t(lang, key, values = {}) {
  const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? ""));
}
